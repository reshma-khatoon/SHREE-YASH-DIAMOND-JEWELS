-- Adapts the EXISTING public.orders table (id, order_id, customers jsonb, items jsonb,
-- price_status, status, created_at) for admin access. Run AFTER 001 (needs is_admin()).
-- Additive only: no table is created, dropped or rewritten, and no rows are modified.
-- The customers and items JSONB columns are left unchanged.

-- 1. Duplicate-submission protection. Nullable, so existing rows stay valid
-- (Postgres allows many NULLs in a unique index).
alter table public.orders add column if not exists idempotency_key uuid;
create unique index if not exists orders_idempotency_key_uidx on public.orders (idempotency_key);

-- 2. order_id is generated by the server (SYDJ-YYYY-XXXXXXXX); make sure it is unique.
-- If this fails, duplicate order_id values already exist: stop and tell me.
create unique index if not exists orders_order_id_uidx on public.orders (order_id);

create index if not exists orders_created_idx on public.orders (created_at desc);

-- 3. Status values. NOT VALID: checks new/updated rows only, never existing rows.
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'orders_status_check_v2') then
    alter table public.orders add constraint orders_status_check_v2
      check (status in ('pending', 'confirmed', 'shipped', 'delivered', 'cancelled')) not valid;
  end if;
end $$;

-- 4. RLS: only the admin can read, update status, or delete. Inserts come from Express
-- with the service-role key (bypasses RLS). Anonymous visitors have no policy at all.
alter table public.orders enable row level security;

drop policy if exists admin_select on public.orders;
drop policy if exists admin_update on public.orders;
drop policy if exists admin_delete on public.orders;
create policy admin_select on public.orders for select to authenticated using (public.is_admin());
create policy admin_update on public.orders for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy admin_delete on public.orders for delete to authenticated using (public.is_admin());

-- 5. Grants: reset client roles, then allow select, delete and status-only updates.
revoke all on public.orders from anon, authenticated;
grant select, delete on public.orders to authenticated;
grant update (status) on public.orders to authenticated;
